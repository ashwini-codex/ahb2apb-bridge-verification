#!/usr/bin/env python3
"""
Bug-injection campaign: rebuild the bridge with +define+INJECT_BUG_<n> and show
that the testbench catches every bug, and with which checker.

  python3 scripts/bug_inject.py            # all bugs, all directed tests + short random
  python3 scripts/bug_inject.py --save     # also write docs/results/bug_injection.md

A bug counts as DETECTED only if at least one test FAILS with it injected.
Every log is in logs/bug<n>_<test>_1.log.
"""
import argparse
import collections
import concurrent.futures as cf
import datetime
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import regress  # noqa: E402

ROOT = regress.ROOT
BUGS = {
    1: "PADDR changes during wait states (address register enable missing HREADY qualification)",
    2: "PENABLE asserted in the same cycle as PSEL (SETUP phase skipped)",
    3: "Second ERROR cycle missing (ERR1 returns to IDLE with HRESP=0)",
    4: "Wrong PSEL decode (slave 2 decoded with slave 1's 4KB size)",
}
TESTS = regress.DIRECTED + ["random_regress"]
EXTRA = {"random_regress": ("+NUM_TXNS=300",)}


def analyse(log_path):
    txt = open(os.path.join(ROOT, log_path)).read()
    sva = collections.OrderedDict()
    for m in re.finditer(r"^\s+(\S+)\s+failed (\d+) time\(s\)", txt, re.M):
        sva[m.group(1)] = int(m.group(2))
    sb = collections.Counter(m.group(1) for m in re.finditer(r"SB MISMATCH\s+(\S+)", txt))
    proto = len(re.findall(r"PROTOCOL ERROR", txt))
    first = re.search(r"^\[(\d+)\] (SVA FAIL: \S+|SB MISMATCH.*|APB S\d PROTOCOL ERROR.*)$", txt, re.M)
    return sva, sb, proto, (first.group(0) if first else "")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--save", action="store_true")
    ap.add_argument("--bugs", default="1,2,3,4")
    args = ap.parse_args()
    os.makedirs(os.path.join(ROOT, "logs"), exist_ok=True)
    os.makedirs(os.path.join(ROOT, "cov"), exist_ok=True)

    md = []
    all_detected = True
    for n in [int(b) for b in args.bugs.split(",")]:
        print(f"\n=== INJECT_BUG_{n}: {BUGS[n]}")
        regress.build(n)
        binary = os.path.join(ROOT, f"build/bug{n}/Vtb_top")
        with cf.ThreadPoolExecutor(max_workers=os.cpu_count()) as ex:
            res = list(ex.map(lambda t: regress.run_one(binary, t, 1, f"bug{n}", EXTRA.get(t, ())), TESTS))
        failing = [r for r in res if r["status"] != "PASS"]
        detected = bool(failing)
        all_detected &= detected
        sva_tot, sb_tot, proto_tot, firsts = collections.Counter(), collections.Counter(), 0, []
        for r in failing:
            sva, sb, proto, first = analyse(r["log"])
            sva_tot.update(sva)
            sb_tot.update(sb)
            proto_tot += proto
            firsts.append((r["test"], first))
        for r in res:
            print(f"  {r['status']:4}  {r['test']:15} {r['reasons']}")
        print(f"  -> {'DETECTED' if detected else 'NOT DETECTED'} by {len(failing)}/{len(res)} tests")
        print(f"     assertions : {dict(sva_tot) or '-'}")
        print(f"     scoreboard : {dict(sb_tot) or '-'}")
        print(f"     APB slave protocol checks: {proto_tot}")
        md.append(f"## INJECT_BUG_{n}: {BUGS[n]}\n")
        md.append(f"**{'DETECTED' if detected else 'NOT DETECTED'}**, {len(failing)}/{len(res)} tests fail.\n")
        md.append("| Test | Status | Reasons |\n|---|---|---|")
        for r in res:
            md.append(f"| {r['test']} | {r['status']} | {r['reasons'] or '-'} |")
        md.append("\nAssertion failures (summed over failing tests):\n")
        md.append("\n".join(f"- `{k}`: {v}" for k, v in sva_tot.most_common()) or "- none")
        md.append("\nScoreboard mismatches by field (first 20 printed per test):\n")
        md.append("\n".join(f"- `{k}`: {v}" for k, v in sb_tot.most_common()) or "- none")
        md.append(f"\nAPB slave-model protocol errors: {proto_tot}\n")
        md.append("First failure message per failing test:\n")
        md.append("\n".join(f"- {t}: `{f}`" for t, f in firsts if f) + "\n")

    if args.save:
        ver = subprocess.run(["verilator", "--version"], stdout=subprocess.PIPE, text=True).stdout.strip()
        stamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
        with open(os.path.join(ROOT, "docs/results/bug_injection.md"), "w") as f:
            f.write(f"# Bug-injection results\n\nGenerated by `scripts/bug_inject.py` on {stamp} with {ver}. "
                    f"Each bug is a separate build (`make compile BUG=<n>`); every test runs with seed 1, "
                    f"random_regress with 300 transactions.\n\n" + "\n".join(md))
        print("\nWrote docs/results/bug_injection.md")
    sys.exit(0 if all_detected else 1)


if __name__ == "__main__":
    main()
